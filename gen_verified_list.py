import csv
import re

BS = chr(92)  # backslash, avoids Python escape interpretation

rows = list(csv.DictReader(open('phase5/reports/EQUATION_AUDIT.csv', newline='', encoding='utf-8')))
verified = [r for r in rows if r['status'].startswith('VERIFIED')]


def secnum(r):
    s = r['section']
    if s == 'B':
        return (99, 'B')
    return (int(s), s)


verified.sort(key=lambda r: (secnum(r)[0], r['audit_id']))


def clean(text):
    """Remove process/internal language from assumption/limit text."""
    # Remove "the script"/"The script" and script+verb constructions
    text = re.sub(r'\b[Tt]he script\b', '', text)
    text = re.sub(r'\b[Ss]cript (checks|verifies|confirms|tests|retains)\b', '', text, flags=re.I)
    # Remove standalone process verbs when they refer to the checking process
    text = re.sub(r'\bverifies?\b', '', text, flags=re.I)
    text = re.sub(r'\bconfirms?\b', '', text, flags=re.I)
    text = re.sub(r'\bchecks?\b', '', text, flags=re.I)
    text = re.sub(r'\bretains?\b', '', text, flags=re.I)
    text = re.sub(r'\bthe verifier\b', '', text, flags=re.I)
    # Remove standalone "script" references (internal tooling)
    text = re.sub(r'\bscript\b', '', text, flags=re.I)
    # Replace "Eq. (N.N)" and "Eq. N.N" style references
    text = re.sub(r'Eq\. \(([^)]+)\)', r'\1', text)
    text = re.sub(r'Eq\. ([0-9]+\.[0-9]+)', r'\1', text)
    # Remove internal OCL references
    text = re.sub(r'\s*OCL-\d+', '', text)
    text = re.sub(r'\s*see\s+OCL-\d+', '', text)
    # Collapse whitespace
    text = re.sub(r'\s+', ' ', text).strip()
    # Capitalize first letter
    if text:
        text = text[0].upper() + text[1:]
    # Clean up double periods and trailing punctuation
    text = re.sub(r'\.\s*\.', '.', text)
    text = text.rstrip('. ')
    return text


def how_checked(status):
    """Return the 'how checked' phrase based on verification status (no trailing period)."""
    if status.startswith('VERIFIED-SYMBOLIC'):
        return "Checked symbolically by computer algebra"
    if status.startswith('VERIFIED-SOURCE'):
        return "Compared with the printed equation in the cited source"
    return ""


def readable_label(label):
    """Replace UNNUMBERED-DISPLAY-n with a readable description."""
    if label.startswith('UNNUMBERED-DISPLAY'):
        # Extract section number from context: label is just UNNUMBERED-DISPLAY-13
        # We need the section from the row; handled in caller
        return None  # caller supplies section-based description
    return label


lines = []
lines.append("% NOTE: verified_list.tex is an orphan copy generated by gen_verified_list.py.")
lines.append("% The file actually included in the build (via main.tex -> \\input{sections/sec12_comparative})")
lines.append("% is phase5/master/sections/sec12_comparative.tex. This file is regenerated")
lines.append("% from phase5/reports/EQUATION_AUDIT.csv but is not \\input'd anywhere.")
lines.append("")
lines.append(BS + "subsection{Verified equation register: assumptions and limits}")
lines.append(BS + "label{sec:12.verified_register}")
lines.append("")
lines.append("The displayed equations were checked within the stated scope; each entry gives the")
lines.append("assumptions under which the check holds and the limits beyond which it does not apply.")
lines.append("Conformance statements are restricted to the displayed equations and the cited sources;")
lines.append("they are not convergence, stability, or source-transcription results beyond the stated scope.")
lines.append("")
lines.append(BS + "begin{description}")
for r in verified:
    label = r['label']
    section = r['section']
    assumptions = clean(r['scope_and_assumptions'].strip())
    raw_limits = r['negative_test'].strip()
    limits = clean(raw_limits)
    checked = how_checked(r['status'])

    # Build readable label: replace UNNUMBERED-DISPLAY-n with description
    if label.startswith('UNNUMBERED-DISPLAY'):
        display_label = f"the unnumbered display in Section {section}"
    else:
        display_label = f"{BS}eqref{{{label}}} (Section~{section})"

    # Assemble the entry text: assumptions + checked + limits
    parts = []
    if assumptions:
        parts.append(assumptions)
    if checked:
        parts.append(checked)
    # Only include limits if it's not empty and not a placeholder.
    # Check the raw value first: if it says "Not recorded" or similar,
    # the cleaned text is just a remnant of the placeholder, not real content.
    raw_is_placeholder = (
        not raw_limits
        or raw_limits.lower().startswith('not recorded')
        or raw_limits.lower() in ('none', 'n/a')
        or raw_limits.lower().startswith('see script header')
        or raw_limits.lower().startswith('see header')
    )
    limits_is_placeholder = (
        not limits
        or limits.lower() in ('none', 'n/a')
    )
    if not raw_is_placeholder and not limits_is_placeholder:
        parts.append(f"Limits: {limits}")

    entry_text = ". ".join(p.rstrip('.') for p in parts)
    if entry_text and not entry_text.endswith('.'):
        entry_text += "."

    lines.append("")
    lines.append(f"  {BS}item[{display_label}] {entry_text}")
lines.append(BS + "end{description}")
lines.append("")

open('/home/user/le/verified_list.tex', 'w', encoding='utf-8').write(chr(10).join(lines))
print("wrote", len(verified), "items to verified_list.tex (orphan copy; source of truth is sec12_comparative.tex)")
